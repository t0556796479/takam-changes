"""Extract the text of a Takam instruction (.docx) as a list of blocks.

Each block is one paragraph, together with the heading it appears under, so a
change can later be reported as "in section 'Parking'".

Design notes:
- Only body paragraphs are read. Tables are deliberately skipped (a documented
  limitation of the POC).
- Section numbers (e.g. 2.2.1) are generated by Word's auto-numbering and are
  not part of the text, so headings are used to locate changes instead.
"""
from dataclasses import dataclass
from pathlib import Path

import docx

# Paragraph styles used in Takam documents that are always headings.
HEADING_STYLE_PREFIXES = ("כותרת", "נספח - כותרת", "Heading")
# Paragraphs in these styles can be either a sub-heading or regular text.
SECTION_STYLE_PREFIX = "סעיף"
MAX_SUBHEADING_WORDS = 6


@dataclass(frozen=True)
class Block:
    text: str
    heading: str          # e.g. "הנחיות לביצוע > חניית הרכב"
    is_heading: bool


class ExtractionError(Exception):
    pass


def _is_main_heading(style_name: str) -> bool:
    return style_name.startswith(HEADING_STYLE_PREFIXES)


def _is_sub_heading(style_name: str, text: str) -> bool:
    """A short 'סעיף' paragraph without closing punctuation acts as a sub-heading."""
    if not style_name.startswith(SECTION_STYLE_PREFIX):
        return False
    return len(text.split()) <= MAX_SUBHEADING_WORDS and not text.endswith((".", ":", ";", ","))


def extract_blocks(path: Path) -> list[Block]:
    try:
        document = docx.Document(str(path))
    except Exception as e:  # python-docx raises several low-level error types
        raise ExtractionError(f"Cannot read {path}: {e}") from e

    blocks: list[Block] = []
    main, sub = "", ""
    for p in document.paragraphs:
        text = " ".join(p.text.split())
        if not text:
            continue
        style = p.style.name if p.style is not None else ""
        if _is_main_heading(style):
            main, sub = text, ""
            blocks.append(Block(text, main, True))
        elif _is_sub_heading(style, text):
            sub = text
            blocks.append(Block(text, _join(main, sub), True))
        else:
            blocks.append(Block(text, _join(main, sub), False))
    return blocks


def _join(main: str, sub: str) -> str:
    return f"{main} > {sub}" if main and sub else (main or sub)
